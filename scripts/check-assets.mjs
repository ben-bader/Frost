#!/usr/bin/env node
// Validates docs/assets SVGs against GitHub-rendering rules.
// Run: pnpm docs:check-assets
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ASSETS = path.join(root, "docs", "assets");
const MAX_FILE = 150 * 1024;
const MAX_TOTAL = 1024 * 1024;

const failures = [];
const files = fs.readdirSync(ASSETS).filter((f) => f.endsWith(".svg"));
let total = 0;

// Raster provenance: every embedded PNG data URI must hash-match a
// derivative recorded in scripts/logo-src/manifest.json, which itself must
// trace back to a file in examples/starter/public.
const manifestPath = path.join(root, "scripts", "logo-src", "manifest.json");
const allowedRaster = new Map(); // sha256 -> manifest entry
if (fs.existsSync(manifestPath)) {
  for (const e of JSON.parse(fs.readFileSync(manifestPath, "utf8"))) {
    const embedded = path.join(root, e.embedded);
    if (!fs.existsSync(embedded)) { failures.push(`manifest: missing ${e.embedded}`); continue; }
    const src = path.join(root, e.source);
    if (!fs.existsSync(src)) { failures.push(`manifest: source ${e.source} not found`); continue; }
    const sha = crypto.createHash("sha256").update(fs.readFileSync(embedded)).digest("hex");
    if (sha !== e.embeddedSha256) failures.push(`manifest: ${e.embedded} hash mismatch`);
    allowedRaster.set(e.embeddedSha256, e);
  }
} else {
  failures.push("scripts/logo-src/manifest.json missing");
}
const RASTER_DATA = /data:image\/(png|jpe?g|gif|webp|bmp);base64,([A-Za-z0-9+/=]+)/g;

// Allowed visible strings (generated by build-readme-assets.mjs from real
// repo strings and the captured overlay payload).
const allowedStrings = new Set(
  JSON.parse(fs.readFileSync(path.join(ASSETS, "allowed-strings.json"), "utf8"))
    .strings.map((s) => s.trim()),
);
const decodeEntities = (s) =>
  s.replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&#39;/g, "'");

const BANNED = [
  [/<script/i, "<script>"],
  [/<foreignObject/i, "<foreignObject>"],
  // xmlns namespaces and localhost URLs in text content are not fetched
  [/https?:\/\/(?!www\.w3\.org\/|localhost|127\.0\.0\.1)/i, "external URL"],
  [/@import/i, "@import"],
  [/xlink:href\s*=\s*["'](?!#)/i, "external xlink:href"],
  [/href\s*=\s*["'](?!#|data:)/i, "external href"],
];
for (const f of files) {
  const p = path.join(ASSETS, f);
  const text = fs.readFileSync(p, "utf8");
  const size = Buffer.byteLength(text);
  total += size;
  if (size > MAX_FILE) failures.push(`${f}: ${size}B exceeds 150KB`);
  if (!/<svg[^>]*viewBox=/i.test(text)) failures.push(`${f}: missing viewBox`);
  for (const [re, what] of BANNED) {
    if (re.test(text)) failures.push(`${f}: contains ${what}`);
  }
  // Raster data URIs are allowed only for manifest-verified logo derivatives.
  for (const m of text.matchAll(RASTER_DATA)) {
    const sha = crypto.createHash("sha256").update(Buffer.from(m[2], "base64")).digest("hex");
    if (!allowedRaster.has(sha)) failures.push(`${f}: unverified embedded raster (sha256 ${sha.slice(0, 12)}…)`);
  }
  // <image> elements may only reference verified data-URI rasters.
  for (const m of text.matchAll(/<image\b[^>]*?href="([^"]+)"/g)) {
    if (!/^data:image\/png;base64,/.test(m[1])) failures.push(`${f}: <image> with non-PNG-data href`);
  }
  // Every visible string must come from the allowed-strings list. Lines
  // built from styled runs are checked per <tspan>; plain <text> per element.
  for (const m of text.matchAll(/<text\b[^>]*>([\s\S]*?)<\/text>/g)) {
    const inner = m[1];
    const tspans = [...inner.matchAll(/<tspan\b[^>]*>([\s\S]*?)<\/tspan>/g)];
    const parts = tspans.length
      ? tspans.map((t) => t[1])
      : [inner];
    for (const part of parts) {
      const visible = decodeEntities(part.replace(/<[^>]+>/g, "")).trim();
      if (visible && !allowedStrings.has(visible)) {
        failures.push(`${f}: text "${visible.slice(0, 60)}" not in allowed-strings.json`);
      }
    }
  }
  // animation rules: CSS keyframes only, transform/opacity only,
  // reduced-motion guard required when animation present
  if (/animation:|@keyframes|<animate/.test(text)) {
    if (/<animate/.test(text)) failures.push(`${f}: SMIL <animate> (use CSS transform/opacity)`);
    if (!/prefers-reduced-motion/.test(text)) {
      failures.push(`${f}: animation without prefers-reduced-motion guard`);
    }
    const animProps = [...text.matchAll(/animation:[^;}"]*/g)].map((m) => m[0]);
    for (const a of animProps) {
      if (/animation:\s*[^;]*\b(?!opacity|transform|animation)[a-z-]+\s*[\d.]+s/.test(a) && /\b(width|height|top|left|right|bottom|margin|padding|color|fill|stroke|font-size|background)\b/.test(a)) {
        failures.push(`${f}: suspicious non-transform/opacity animation "${a.trim()}"`);
      }
    }
  }
}
if (total > MAX_TOTAL) failures.push(`total assets ${total}B exceeds 1MB`);
if (files.length === 0) failures.push("no SVG assets found");

// README <img>/<source> references must exist
const readme = fs.readFileSync(path.join(root, "README.md"), "utf8");
for (const m of readme.matchAll(/(?:src|srcset)="(docs\/assets\/[^"]+)"/g)) {
  const rel = m[1].split(" ")[0];
  if (!fs.existsSync(path.join(root, rel))) failures.push(`README references missing ${rel}`);
}

if (failures.length) {
  console.error("check-assets FAILED:");
  for (const f of failures) console.error(`  - ${f}`);
  process.exit(1);
}
console.log(`check-assets OK — ${files.length} SVGs, ${(total / 1024).toFixed(0)}KB total`);
