/**
 * Generates `.frost/types/routes.d.ts` — ambient route types that
 * augment `@frostjs/react`'s FrostRouteMap so Link hrefs get typed
 * autocomplete for every static page route.
 */
export interface RouteTypeEntry {
  pattern: string;
  kind: string;
  isDynamic: boolean;
  isCatchAll: boolean;
}

export function routeTypesDeclaration(routes: RouteTypeEntry[]): string {
  const paths = [
    ...new Set(
      routes
        .filter((r) => r.kind === "page" && !r.isDynamic && !r.isCatchAll)
        .map((r) => `/${r.pattern}`.replace(/\/+/g, "/") || "/"),
    ),
  ].sort();

  const members = paths.map((p) => `    ${JSON.stringify(p)}: true;`).join("\n");

  return `// Generated by Frost — do not edit. Regenerated on dev/build.
// The trailing export makes this a module so the declare module below
// acts as an augmentation of @frostjs/react rather than shadowing it.

declare module "@frostjs/react" {
  interface FrostRouteMap {
${members || "    // no static routes"}
  }
}

export {};
`;
}
